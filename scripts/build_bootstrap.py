"""Generate the one-time SQL Editor script from the tracked migrations."""

from pathlib import Path

files = sorted(Path("supabase/migrations").glob("*.sql"))
content = "-- Generated by scripts/build_bootstrap.py; one transaction, no data reset.\nBEGIN;\n"
content += "\n".join("-- " + p.name + "\n" + p.read_text(encoding="utf-8") for p in files)
content += "\nCOMMIT;\n"
Path("supabase/bootstrap.sql").write_text(content, encoding="utf-8")
phase5 = Path("supabase/migrations/20261017000100_operations.sql")
if phase5.exists():
    Path("supabase/phase5-upgrade.sql").write_text(
        "-- Phase 5 additive upgrade only; read docs/phase5-migration-impact.md first.\n"
        "BEGIN;\nSELECT pg_advisory_xact_lock(490016000);\n"
        + phase5.read_text(encoding="utf-8")
        + "\nCOMMIT;\n",
        encoding="utf-8",
    )
